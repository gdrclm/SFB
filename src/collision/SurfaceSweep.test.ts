import HavokPhysics from "@babylonjs/havok";
import { readFile } from "node:fs/promises";
import { expect,it } from "vitest";
import { NullEngine } from "@babylonjs/core/Engines/nullEngine";
import { Scene } from "@babylonjs/core/scene";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { HavokPlugin } from "@babylonjs/core/Physics";
import { gameConfig } from "../config/gameConfig";
import { PlatformController } from "../platform/PlatformController";
import { HavokPlatformSweep } from "./HavokPlatformSweep";
import { CollisionResolver } from "./CollisionResolver";
import { SurfaceInteractions } from "../platform/SurfaceInteractions";
import { BallController } from "../ball/BallController";
it("excludes holograms from Havok, opens exact honeycomb holes and still resolves the next collider in the same step",async()=>{
 const engine=new NullEngine(),scene=new Scene(engine);
 const wasm=await readFile(new URL("../../node_modules/@babylonjs/havok/lib/esm/HavokPhysics.wasm",import.meta.url));
 scene.enablePhysics(Vector3.Zero(),new HavokPlugin(true,await HavokPhysics({wasmBinary:Uint8Array.from(wasm).buffer})));
 const plugin=scene.getPhysicsEngine()?.getPhysicsPlugin();if(!(plugin instanceof HavokPlugin))throw Error("Missing Havok");
 const template=gameConfig.platforms[0];if(!template)throw Error("Missing platform");
 const p=new PlatformController(scene,gameConfig,template,false),back=new PlatformController(scene,gameConfig,{...template,id:"behind-surface",position:{x:0,y:-2}});
 p.reactivate(new Vector3(0,0,0),{surface:"hologram",strength:10,strengthLevel:"low",widthScale:4/7.5});
 const sweep=new HavokPlatformSweep(scene,plugin,.5,[p,back]);
 expect(sweep.cast({x:0,y:2,z:0},{x:0,y:-4,z:0})).toBe(back);
 p.deactivate();p.reactivate(new Vector3(0,0,0),{surface:"honeycomb",strength:10,strengthLevel:"low",widthScale:4/7.5});
 expect(sweep.cast({x:0,y:2,z:0},{x:0,y:-4,z:0})).toBe(p);
 p.setSurfaceCells(195);expect(sweep.cast({x:0,y:2,z:0},{x:0,y:-4,z:0})).toBe(back);
 expect(sweep.cast({x:1.7,y:2,z:0},{x:1.7,y:-1,z:0})).toBe(p);
 p.setSurfaceCells(255);
 const ball=new BallController({position:{x:0,y:0,z:0}},{isActive:false,normalizedPosition:0},gameConfig);ball.fallSpeed=6000;
 const actions={bounce:()=>{},chip:()=>{},destroy:()=>{},hurt:()=>{},feather:()=>{}};
 const surfaces=new SurfaceInteractions(ball,()=>[p,back],actions,()=>true,()=>false,()=>1000);
 const resolver=new CollisionResolver(ball,sweep),hits:string[]=[];
 resolver.onCollision(c=>{hits.push(c.platform.id);if(!surfaces.beforeHit(c))c.platform.deactivate();});
 ball.fixedUpdate(1/60);resolver.fixedUpdate();
 expect(hits).toEqual([p.id,back.id]);expect(p.isActive).toBe(true);expect(back.isActive).toBe(false);
 resolver.dispose();p.dispose();back.dispose();scene.dispose();engine.dispose();
});
