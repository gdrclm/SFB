"""Inspect six generated sheets without editing their artwork, encode WebP and
write source-cell bounds for stable GPU sampling. Usage: idle sky/special/advanced,
then destroy sky/special/advanced (six PNG paths). Requires Pillow and ImageMagick.
"""
from pathlib import Path
import hashlib
import json
import subprocess
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
GROUPS = [
    ("sky", ["island", "storm", "nest", "balloons", "web"]),
    ("special", ["hologram", "laser", "honeycomb", "spikes"]),
    ("advanced", ["magnet", "liquid", "resonance", "moving", "wind", "turret"]),
]

def inspect(source, rows, group, mode):
    image = Image.open(source).convert("RGBA")
    assert image.width % 6 == 0 and image.height % rows == 0, image.size
    cellw, cellh = image.width // 6, image.height // rows
    results, bodies = [], []
    for row in range(rows):
        boxes, fingerprints = [], set()
        for col in range(6):
            # The turret's upper 20 px sit in the otherwise empty gap below
            # the preceding fan row. Explicit source bounds keep them with the
            # turret instead of leaking a cannon tip into every wind platform.
            extension = -20 if group == "advanced" and mode == "idle" and row == 5 else -24 if group == "sky" and row == 3 else 0
            limit = 170 if group == "advanced" and mode == "idle" and row == 4 else 200 if group == "sky" and row == 2 else cellh
            cell = image.crop((col*cellw, row*cellh+extension, (col+1)*cellw, row*cellh+limit))
            mask = cell.getchannel("A").point(lambda alpha: 255 if alpha >= 64 else 0)
            bbox = mask.getbbox()
            assert bbox is not None, (source, row, col)
            bbox = (bbox[0],bbox[1]+extension,bbox[2],bbox[3]+extension)
            boxes.append(bbox)
            fingerprints.add(hashlib.sha256(cell.tobytes()).hexdigest())
        assert len(fingerprints) == 6, (source, row, "duplicate frames")
        left, top = max(0, min(b[0] for b in boxes)-2), min(b[1] for b in boxes)-2
        if not (group == "advanced" and mode == "idle" and row == 5 or group == "sky" and row == 3): top = max(0,top)
        right, bottom = min(cellw, max(b[2] for b in boxes)+2), min(cellh, max(b[3] for b in boxes)+2)
        results.append([left, top, right-left, bottom-top])
        b = boxes[0]
        bodies.append([b[0]-left, b[1]-top, b[2]-b[0], b[3]-b[1]])
    return {"size": list(image.size), "cell": [cellw, cellh], "bounds": results, "body": bodies}

sources = sys.argv[1:]
encode = "--layout-only" not in sources
sources = [s for s in sources if s != "--layout-only"]
if len(sources) != 6:
    raise SystemExit(__doc__)
groups = []
for index, (name, kinds) in enumerate(GROUPS):
    group = {"name": name, "kinds": kinds}
    for mode, offset in [("idle", 0), ("destroy", 3)]:
        source = sources[offset+index]
        group[mode] = inspect(source, len(kinds), name, mode)
        target = ROOT / "src/assets/platforms" / f"surface-{mode}-{name}.webp"
        if encode:
            subprocess.run(["magick", source, "-quality", "88", "-define", "webp:alpha-quality=100", str(target)], check=True)
    groups.append(group)
out = ROOT / "src/platform/SurfaceAnimationLayout.ts"
out.write_text("// Generated by tools/build-surface-animation-layout.py; original pixels are unchanged.\n"
               "export const SURFACE_ANIMATION_LAYOUT = " + json.dumps(groups, separators=(",", ":")) + " as const;\n")
print("Verified 180 distinct cells (six idle and six destruction frames for fifteen objects).")
